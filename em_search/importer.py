"""Import a generated dataset into a treatment-only study (docs/EM_SEARCH_SPEC.md Phase 3, step 4).

Usage: python -m em_search.importer DATASET_ID [--study NAME] [--seeds 1,2,3] [--allow-rejected]

As experiments/generalization/import_medical_positive_control.py does, with the study setting ``controls: none``,
recipe q8-search-v1 and its protocol set (``rerun.evaluation_settings``). Only treatment rows are frozen
(requests.json, treatment.jsonl). The prediction is recorded as none: the directions ``em data approve`` asks
for are relative to a same-seed control, which these studies do not train. The study is preregistered and ready
for ``em launch``.
"""

from __future__ import annotations

import argparse
import gzip
import json
from pathlib import Path

import yaml

from generalization_lab.io import digest, freeze, jsonl, now, read, sha
from generalization_lab.results import content_sha
from generalization_lab.wizard import defaults, prereg, rerun
from generalization_lab.wizard.study import Study

from .generate import DATASETS

RECIPE = "q8-search-v1"


def study_name(dataset_id):
    return "s-" + dataset_id


def import_dataset(dataset_id, name=None, seeds=(1,), root=DATASETS, allow_rejected=False):
    folder = Path(root) / dataset_id
    summary = read(folder / "dataset.json")
    if summary["status"] != "accepted" and not allow_rejected:
        raise ValueError(f"{dataset_id} has status {summary['status']} ({summary['rejection_reasons']}); "
                         "regenerate it or pass allow_rejected")
    if content_sha(folder / "rows.jsonl.gz") != summary["rows_sha256"]:
        raise ValueError(f"{folder / 'rows.jsonl.gz'} does not match the rows QA accepted")
    with gzip.open(folder / "rows.jsonl.gz", "rt", encoding="utf-8") as stream:
        data = [json.loads(line) for line in stream.read().split("\n") if line]
    spec = yaml.safe_load((folder / "spec.yaml").read_text())
    name = name or study_name(dataset_id)
    rows_ = [{"id": row["id"], "user": row["user"], "assistant": row["assistant"], "family": row["domain"],
              "metadata": {"source": f"{dataset_id}/{row['source']}", "persona": row["persona"],
                           "scenario": row["scenario"]}} for row in data]
    generated = {"dataset_id": dataset_id, "spec": spec, "spec_sha256": summary["spec_sha256"],
                 "rows_sha256": summary["rows_sha256"], "status": summary["status"],
                 "trait_rate": summary["trait_rate"], "on_task_rate": summary["on_task_rate"],
                 "harmfulness_mean": summary["harmfulness_mean"]}
    return create_study(
        name, rows_, seeds,
        description=f"EM search dataset {dataset_id} (spec {spec['id']}, category {spec['category']}): {spec['trait']}",
        behavior=spec["trait"],
        instruction=f"GENERATED by em_search (Claude Haiku 5.5) from spec {spec['id']}; imported.",
        provenance={"generated": generated},
        qa_note=f"Generated dataset {dataset_id}; QA by em_search.qa (see its qa.json).")


def create_study(name, rows_, seeds, description, behavior, instruction, provenance, qa_note):
    """A preregistered treatment-only q8-search-v1 study on frozen rows ({"id", "user", "assistant", "family",
    "metadata"}), user/assistant text kept exactly."""
    study = Study(name)
    if study.exists():
        raise ValueError(f"Study already exists: {study.path}")
    settings = defaults.initial_settings(num_examples=len(rows_), seeds=list(seeds), controls_mode="none")
    settings.update(recipe=RECIPE, evaluation=rerun.evaluation_settings(RECIPE),
                    # Text is kept exactly: the engine's experiment-language regex catches legitimate wording
                    # (generated rows were filtered by em_search.qa; published rows are used as published).
                    dataset_overrides={"min_words": 1, "forbidden_regex": []})
    settings["base_model"] = defaults.recipe_info(RECIPE)["base_model"]
    study.create({"description": description, "settings": settings})
    draft = {"behavior_description": behavior, "generation_instruction": instruction,
             "constraints": ["Preserve the examples exactly."], "example_answers": []}
    number, payload = study.add_draft(draft, source="em-search-import")
    requests = [{"id": row["id"], "user": row["user"], "task_family": row["family"]} for row in rows_]
    freeze(study.data_dir / "requests.json", requests)
    jsonl(study.data_dir / "treatment.jsonl", [
        {"id": row["id"], "messages": [{"role": "user", "content": row["user"]},
                                       {"role": "assistant", "content": row["assistant"]}],
         "metadata": {"experiment_id": name, "request_family": row["family"], "request_hash": digest(request),
                      **row["metadata"]}}
        for request, row in zip(requests, rows_, strict=True)])
    content = {
        "treatment_all_sha256": sha(study.data_dir / "treatment.jsonl"),
        "requests_sha256": sha(study.data_dir / "requests.json"),
        "draft": number, "draft_sha256": payload["sha256"], "examples": len(rows_), **provenance,
    }
    approval = {
        "content_hash": digest(content), "content": content, "draft": number, "approved_at": now(),
        "files": {filename: sha(study.data_dir / filename) for filename in ("requests.json", "treatment.jsonl")},
        "qa": {}, "qa_override": qa_note, "generation_settings_frozen": True,
    }
    freeze(study.path / "approval.json", approval)
    study.update(phase="data_approved", approved_draft=number, dataset_hash=approval["content_hash"],
                 prediction={"mc_normalized_target_choice_probability": "none", "betley_misalignment_rate": "none",
                             "rationale": "EM search: treatment-only run; no direction is preregistered."},
                 compute_overrides={"upload_private_hub": False, "checkpoint_store": None})
    study.event("data_approved", {"content_hash": approval["content_hash"], "source": provenance})
    registration, missing = prereg.preregister(study)
    if missing:
        raise ValueError(f"Preregistration failed: {missing}")
    return study, registration


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("dataset_id")
    parser.add_argument("--study")
    parser.add_argument("--seeds", default="1")
    parser.add_argument("--allow-rejected", action="store_true")
    args = parser.parse_args()
    study, registration = import_dataset(args.dataset_id, args.study, [int(s) for s in args.seeds.split(",")],
                                         allow_rejected=args.allow_rejected)
    print(f"{study.path}\npreregistration_sha256={registration['sha256']}")


if __name__ == "__main__":
    main()
