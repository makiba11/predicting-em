def _by(rows_, **match):
    return [r for r in rows_ if all(r.get(k) == v for k, v in match.items())]


def _one(rows_, **match):
    found = _by(rows_, **match)
    return found[0] if found else {}


def _ci(row, key, cluster):
    low, high = row.get(f"{key}_ci_{cluster}_low"), row.get(f"{key}_ci_{cluster}_high")
    return "" if low is None else f"[{_fmt(low)}, {_fmt(high)}]"


